def get_glyph(ch: str) -> Glyph:
    if ch in _ASCII:
        return _ASCII[ch]
    if ch in _CJK:
        return _CJK[ch]
    upper = ch.upper()
    if upper in _ASCII:
        return _ASCII[upper]
    # 未知字符画成小叉，避免静默丢字
    return [[(0.2, 0.2), (0.8, 0.8)], [(0.2, 0.8), (0.8, 0.2)]]


def iter_stroke_segments(
    text: str,
    x: float,
    y: float,
    size: float,
    *,
    tracking: float = 1.05,
) -> Iterable[tuple[float, float, float, float]]:
    """产出页面坐标下的线段 (x0,y0,x1,y1)。y 为字身基线。"""
    cursor = x
    for ch in text:
        glyph = get_glyph(ch)
        for stroke in glyph:
            if len(stroke) < 2:
                continue
            for (x0, y0), (x1, y1) in zip(stroke, stroke[1:]):
                yield (
                    cursor + x0 * size,
                    y + y0 * size,
                    cursor + x1 * size,
                    y + y1 * size,
                )
        cursor += size * tracking


def measure_width(text: str, size: float, tracking: float = 1.05) -> float:
    return len(text) * size * tracking
